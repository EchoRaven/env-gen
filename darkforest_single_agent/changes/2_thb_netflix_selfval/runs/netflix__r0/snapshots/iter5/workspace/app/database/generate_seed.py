#!/usr/bin/env python3
"""Generate init/02_seed.sql from design/dataset/titles.json.

Usage: python3 app/database/generate_seed.py design/dataset/titles.json
"""
import base64, hashlib, json, sys
from pathlib import Path

# Real clip lengths (seconds), measured from the fragmented MP4s in assets/video.
CLIPS = [("clip_35079542.mp4", 15), ("clip_30070091.mp4", 13), ("clip_18972999.mp4", 11),
         ("clip_27152549.mp4", 9), ("clip_30997958.mp4", 8), ("clip_27152555.mp4", 7)]


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def pw_hash(password, salt):
    dk = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 120_000)
    return "pbkdf2_sha256$120000$%s$%s" % (base64.b64encode(salt).decode(), base64.b64encode(dk).decode())


def main(src):
    rows = json.loads(Path(src).read_text())
    # Rows without artwork or genre cannot be shown honestly; skip them.
    rows = [r for r in rows if r.get("poster") and r.get("backdrop") and r.get("genres")]
    out = ["-- GENERATED by app/database/generate_seed.py from design/dataset/titles.json", "BEGIN;"]
    genres = sorted({g for r in rows for g in r["genres"]})
    gid = {g: i + 1 for i, g in enumerate(genres)}
    out += [f"INSERT INTO genres (id, name) VALUES ({gid[g]}, {q(g)});" for g in genres]
    out.append(f"SELECT setval('genres_id_seq', {len(genres)});")

    movies = [r for r in rows if r["kind"] == "movie"]
    series = [r for r in rows if r["kind"] == "series"]
    # The dataset lists TMDB weekly-trending titles first (ids 1-20 movies, 21-40 series).
    top10 = {r["id"]: i + 1 for i, r in enumerate(movies[:10])}
    top10.update({r["id"]: i + 1 for i, r in enumerate(series[:10])})
    trending = {}
    tm = [r for r in movies if r["id"] <= 20]
    ts = [r for r in series if 21 <= r["id"] <= 40]
    rank = 1
    for a, b in zip(tm, ts):
        trending[a["id"]] = rank; trending[b["id"]] = rank + 1; rank += 2

    for i, r in enumerate(rows):
        clip, secs = CLIPS[r["id"] % len(CLIPS)]
        strip = lambda p: "/" + p  # assets/... served by the frontend at /assets/...
        out.append(
            "INSERT INTO titles (id, name, kind, year, genre, maturity_rating, rating, synopsis, poster,"
            " backdrop, video_url, duration, top10_rank, trending_rank, language) VALUES ("
            + ", ".join(q(v) for v in [r["id"], r["name"], r["kind"], r.get("year"), r.get("genre"),
                                         r.get("maturity_rating"), r.get("rating"), r.get("synopsis"),
                                         strip(r["poster"]), strip(r["backdrop"]),
                                         f"/assets/video/{clip}", secs, top10.get(r["id"]),
                                         trending.get(r["id"]), r.get("language")]) + ");")
        for g in r["genres"]:
            out.append(f"INSERT INTO title_genres (title_id, genre_id) VALUES ({r['id']}, {gid[g]});")
        if r["kind"] == "series":
            # Episode metadata is not in the dataset; the catalog exposes numbered episodes that
            # play the title's real clip. Only E1 carries the show's real synopsis.
            seasons = 2 if r["id"] % 3 == 0 else 1
            for s in range(1, seasons + 1):
                n_eps = 4 + (r["id"] + s) % 3
                for e in range(1, n_eps + 1):
                    eclip, esecs = CLIPS[(r["id"] + s + e) % len(CLIPS)]
                    syn = r.get("synopsis") if (s == 1 and e == 1) else None
                    out.append(
                        "INSERT INTO episodes (title_id, season, number, name, synopsis, duration, thumbnail)"
                        f" VALUES ({r['id']}, {s}, {e}, {q('Episode %d' % e)}, {q(syn)}, {esecs},"
                        f" {q(strip(r['backdrop']))});")

    # Demo account: demo@netflix.local / netflix123 with three profiles.
    out.append("INSERT INTO users (id, email, password_hash, name) VALUES (1, 'demo@netflix.local', "
               + q(pw_hash("netflix123", b"netflix-demo-salt")) + ", 'Demo');")
    out.append("SELECT setval('users_id_seq', 1);")
    out.append("INSERT INTO profiles (id, user_id, name, avatar, is_kids) VALUES"
               " (1, 1, 'Demo', 'blue', FALSE), (2, 1, 'Alex', 'red', FALSE), (3, 1, 'Kids', 'kids', TRUE);")
    out.append("SELECT setval('profiles_id_seq', 3);")
    # A little starting state for the demo's first profile only (profile 2 starts empty).
    out.append("INSERT INTO my_list (profile_id, title_id) VALUES (1, 22), (1, 36), (1, 42);")
    out.append("INSERT INTO ratings (profile_id, title_id, value) VALUES (1, 36, 2), (1, 25, 1);")
    eid = "(SELECT id FROM episodes WHERE title_id=24 AND season=1 AND number=2)"
    out.append("INSERT INTO continue_watching (profile_id, title_id, episode_id, progress_seconds) VALUES"
               f" (1, 24, {eid}, 4), (1, 2, NULL, 6);")
    out.append("COMMIT;")
    dest = Path(__file__).resolve().parent / "init" / "02_seed.sql"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({len(rows)} titles, {len(genres)} genres)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "design/dataset/titles.json")
