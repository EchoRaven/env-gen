"""Generate deterministic PostgreSQL seed data from the supplied catalog."""

import base64
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DATASET = ROOT / "design" / "dataset" / "titles.json"
OUTPUT = Path(__file__).resolve().parent / "init" / "002_seed.sql"

SERIES_TOP_10 = [28, 22, 36, 24, 25, 26, 34, 38, 23, 27]
MOVIE_TOP_10 = [2, 11, 1, 7, 42, 5, 15, 18, 10, 41]
VIDEO_CLIPS = [
    "clip_30070091.mp4",
    "clip_18972999.mp4",
    "clip_27152549.mp4",
    "clip_27152555.mp4",
    "clip_30997958.mp4",
    "clip_35079542.mp4",
]


def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def password_hash(password: str) -> str:
    salt = "netflix-demo-salt"
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 260000)
    return "pbkdf2_sha256$260000$%s$%s" % (
        salt,
        base64.urlsafe_b64encode(digest).decode().rstrip("="),
    )


def main():
    titles = json.loads(DATASET.read_text())
    genre_names = sorted({g for title in titles for g in title.get("genres", [])})
    genre_ids = {name: index + 1 for index, name in enumerate(genre_names)}
    movie_ranks = {title_id: index + 1 for index, title_id in enumerate(MOVIE_TOP_10)}
    series_ranks = {title_id: index + 1 for index, title_id in enumerate(SERIES_TOP_10)}

    lines = [
        "-- Netflix clone seed data. Generated by generate_seed.py.",
        "BEGIN;",
        "",
        "INSERT INTO users (id, email, password_hash, name) VALUES",
        f"  (1, {q('demo@netflix.com')}, {q(password_hash('password123'))}, {q('Demo Viewer')})",
        "ON CONFLICT (email) DO NOTHING;",
        "SELECT setval('users_id_seq', (SELECT MAX(id) FROM users));",
        "",
        "INSERT INTO profiles (id, user_id, name, avatar, is_kids) VALUES",
        "  (1, 1, 'Alex', 'red', FALSE),",
        "  (2, 1, 'Maya', 'blue', FALSE),",
        "  (3, 1, 'Little Ones', 'yellow', TRUE)",
        "ON CONFLICT (id) DO NOTHING;",
        "SELECT setval('profiles_id_seq', (SELECT MAX(id) FROM profiles));",
        "",
        "INSERT INTO titles (id, name, kind, year, genre, maturity_rating, rating, synopsis, poster, backdrop, video_url, duration, top10_rank, language) VALUES",
    ]

    title_rows = []
    for title in titles:
        poster = "/" + title["poster"]
        backdrop = "/" + (title.get("backdrop") or title["poster"])
        clip = VIDEO_CLIPS[(title["id"] - 1) % len(VIDEO_CLIPS)]
        rank = movie_ranks.get(title["id"]) if title["kind"] == "movie" else series_ranks.get(title["id"])
        duration = 96 + (title["id"] * 7) % 35 if title["kind"] == "movie" else 42
        title_rows.append(
            "  (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"
            % (
                title["id"], q(title["name"]), q(title["kind"]), q(title["year"]),
                q(title.get("genre") or ""), q(title.get("maturity_rating") or "TV-14"),
                q(title.get("rating") or 0), q(title.get("synopsis") or ""), q(poster),
                q(backdrop), q("/assets/video/" + clip), duration, q(rank),
                q(title.get("language") or "en"),
            )
        )
    lines.append(",\n".join(title_rows) + ";")
    lines += ["", "INSERT INTO genres (id, name) VALUES"]
    lines.append(",\n".join(f"  ({genre_ids[name]}, {q(name)})" for name in genre_names) + ";")
    lines.append("SELECT setval('genres_id_seq', (SELECT MAX(id) FROM genres));")
    lines += ["", "INSERT INTO title_genres (title_id, genre_id) VALUES"]
    tg_rows = []
    for title in titles:
        for genre in title.get("genres", []):
            tg_rows.append(f"  ({title['id']}, {genre_ids[genre]})")
    lines.append(",\n".join(tg_rows) + " ON CONFLICT DO NOTHING;")

    episode_names = [
        "The Beginning", "Crossing Lines", "No Way Back", "The Other Side",
        "Revelations", "The Reckoning", "A New Dawn", "The Long Way Home",
    ]
    lines += ["", "INSERT INTO episodes (title_id, season, number, name, synopsis, duration, thumbnail) VALUES"]
    episode_rows = []
    for title in titles:
        if title["kind"] != "series":
            continue
        backdrop = "/" + (title.get("backdrop") or title["poster"])
        for season in (1, 2):
            for number, episode_name in enumerate(episode_names[:6], start=1):
                synopsis = (
                    f"Season {season}, Episode {number}. The story of {title['name']} unfolds "
                    "as new secrets surface and old alliances are tested."
                )
                episode_rows.append(
                    f"  ({title['id']}, {season}, {number}, {q(episode_name)}, {q(synopsis)}, {q(42)}, {q(backdrop)})"
                )
    lines.append(",\n".join(episode_rows) + " ON CONFLICT DO NOTHING;")

    lines += [
        "",
        "INSERT INTO my_list (profile_id, title_id) VALUES",
        "  (1, 1), (1, 22), (1, 36), (1, 15), (2, 7), (2, 25), (3, 10), (3, 19)",
        "ON CONFLICT DO NOTHING;",
        "",
        "INSERT INTO ratings (profile_id, title_id, value) VALUES",
        "  (1, 22, 2), (1, 1, 1), (2, 36, 1), (2, 7, 2), (3, 10, 1)",
        "ON CONFLICT DO NOTHING;",
        "",
        "INSERT INTO continue_watching (profile_id, title_id, progress_seconds) VALUES",
        "  (1, 22, 1420), (1, 2, 830), (1, 36, 2400)",
        "ON CONFLICT DO NOTHING;",
        "",
        "COMMIT;",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT} ({len(titles)} titles, {len(genre_names)} genres, {len(episode_rows)} episodes)")


if __name__ == "__main__":
    main()
