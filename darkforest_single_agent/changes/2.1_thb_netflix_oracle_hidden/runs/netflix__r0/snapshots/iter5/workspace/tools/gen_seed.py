"""Generate app/database/init/02_seed.sql from design/dataset/titles.json."""
import hashlib, json, os, random, base64
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
titles = json.load(open(os.path.join(ROOT, 'design/dataset/titles.json')))
videos = sorted(os.listdir(os.path.join(ROOT, 'design/assets/video')))

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return 'TRUE' if v else 'FALSE'
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def pw_hash(pw, salt=b'netflixdemo-salt'):
    dk = hashlib.pbkdf2_hmac('sha256', pw.encode(), salt, 200_000)
    return 'pbkdf2_sha256$200000$' + base64.b64encode(salt).decode() + '$' + base64.b64encode(dk).decode()

def asset(p):
    return '/' + p if p else None

out = ['-- Generated by tools/gen_seed.py from design/dataset/titles.json', 'BEGIN;']
genres = []
for t in titles:
    for g in t['genres']:
        if g not in genres: genres.append(g)
genres.sort()
gid = {g: i + 1 for i, g in enumerate(genres)}
for g in genres:
    out.append(f"INSERT INTO genres (id, name) VALUES ({gid[g]}, {q(g)});")

# top 10 ranks: per kind, ordered by rating desc among the most recent titles
rank = {}
for kind in ('movie', 'series'):
    cand = sorted([t for t in titles if t['kind'] == kind and t.get('backdrop')],
                  key=lambda t: (-int(t['year'] or 0), -(t['rating'] or 0), t['id']))[:10]
    cand.sort(key=lambda t: (-(t['rating'] or 0), t['id']))
    for i, t in enumerate(cand): rank[t['id']] = i + 1

rnd = random.Random(42)
for t in titles:
    tid = t['id']
    dur = 85 + (tid * 37) % 60 if t['kind'] == 'movie' else 22 + (tid * 13) % 35
    video = '/assets/video/' + videos[tid % len(videos)]
    backdrop = t.get('backdrop') or t.get('poster')
    out.append(
        "INSERT INTO titles (id, name, kind, year, genre, maturity_rating, rating, synopsis, poster, backdrop, video_url, duration, top10_rank, language) VALUES ("
        + ', '.join([q(tid), q(t['name']), q(t['kind']), q(int(t['year']) if t.get('year') else None), q(t['genre']),
                     q(t['maturity_rating']), q(t['rating']), q(t['synopsis']), q(asset(t['poster'])), q(asset(backdrop)),
                     q(video), q(dur), q(rank.get(tid)), q(t.get('language'))]) + ');')
    for g in t['genres']:
        out.append(f"INSERT INTO title_genres (title_id, genre_id) VALUES ({tid}, {gid[g]});")

ep_id = 0
for t in titles:
    if t['kind'] != 'series': continue
    seasons = 1 + (t['id'] % 3 == 0) + (t['id'] % 5 == 0)
    for s in range(1, seasons + 1):
        n_eps = 4 + (t['id'] + s) % 5
        for n in range(1, n_eps + 1):
            ep_id += 1
            dur = 22 + (t['id'] * 7 + n * 3) % 35
            out.append(
                "INSERT INTO episodes (id, title_id, season, number, name, synopsis, duration, thumbnail) VALUES ("
                + ', '.join([q(ep_id), q(t['id']), q(s), q(n), q(f'Episode {n}'),
                             q(f"Season {s}, episode {n} of {t['name']}."), q(dur),
                             q(asset(t.get('backdrop') or t.get('poster')))]) + ');')

# demo account
out.append(f"INSERT INTO users (id, email, password_hash, name) VALUES (1, 'demo@netflix.local', {q(pw_hash('netflix123'))}, 'Demo');")
out.append("INSERT INTO profiles (id, user_id, name, avatar, is_kids) VALUES (1, 1, 'Demo', 'blue', FALSE), (2, 1, 'Alex', 'red', FALSE), (3, 1, 'Kids', 'kids', TRUE);")
out.append("INSERT INTO my_list (profile_id, title_id) VALUES (1, 36), (1, 24), (1, 2);")
out.append("INSERT INTO continue_watching (profile_id, title_id, progress_seconds) VALUES (1, 22, 4), (1, 42, 6);")
out.append("INSERT INTO ratings (profile_id, title_id, value) VALUES (1, 36, 2);")
for tbl in ['users', 'profiles', 'titles', 'episodes', 'genres', 'title_genres', 'my_list', 'ratings', 'continue_watching']:
    out.append(f"SELECT setval(pg_get_serial_sequence('{tbl}', 'id'), (SELECT COALESCE(MAX(id), 1) FROM {tbl}));")
out.append('COMMIT;')
open(os.path.join(ROOT, 'app/database/init/02_seed.sql'), 'w').write('\n'.join(out) + '\n')
print('ok', len(out))
