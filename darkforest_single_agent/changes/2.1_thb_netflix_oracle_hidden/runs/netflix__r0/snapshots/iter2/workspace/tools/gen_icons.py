import os, re, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
base = os.path.join(ROOT, 'design/assets/icons')
icons = {}
for sub in ('', 'netflix'):
    d = os.path.join(base, sub)
    for f in sorted(os.listdir(d)):
        if not f.endswith('.svg'): continue
        s = open(os.path.join(d, f)).read()
        s = re.sub(r'<!--.*?-->', '', s, flags=re.S)
        s = re.sub(r'\s+', ' ', s).strip()
        s = re.sub(r'\s(width|height)="[^"]*"', '', s, count=2)
        s = re.sub(r'\sclass="[^"]*"', '', s)
        name = ('nf-' if sub else '') + f[:-4]
        icons[name] = s
open(os.path.join(ROOT, 'app/frontend/src/icons.js'), 'w').write(
    '// Generated by tools/gen_icons.py from design/assets/icons (Lucide + Netflix sets)\nexport default ' + json.dumps(icons, indent=1) + ';\n')
print(list(icons))
